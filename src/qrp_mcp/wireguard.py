"""WireGuard configuration (ZA-OPRAVYANE row 335).

WireGuard's key exchange is fixed by the protocol, not chosen in the file: "Curve25519 for
ECDH" (https://www.wireguard.com/protocol/). wg(8)
(https://man7.org/linux/man-pages/man8/wg.8.html): "There are two top level sections --
Interface and Peer"; "PrivateKey -- a base64 private key generated by wg genkey";
"PublicKey -- a base64 public key calculated by wg pubkey"; "PresharedKey -- a base64
preshared key generated by wg genpsk. Optional", which the protocol page describes as "an
additional layer of symmetric-key crypto ... (for, say, post-quantum resistance)". So each
section is an X25519 key establishment, and the file's PrivateKey is private key material.
Whether a peer sets a PresharedKey is said beside it; it does not change the family.
"""

from __future__ import annotations

import re
from typing import Any

_SECTION = re.compile(r"^\s*\[(Interface|Peer)\]\s*$")
_KEY = re.compile(r"^\s*(PrivateKey|PublicKey|PresharedKey)\s*=\s*([A-Za-z0-9+/]{43}=)\s*$")


def scan(lines: list[str]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """(X25519 rows, private key rows) of a WireGuard configuration; empty for any other file."""
    sections: list[dict[str, Any]] = []
    keys: list[dict[str, Any]] = []
    for number, line in enumerate(lines, 1):
        section = _SECTION.match(line)
        if section:
            sections.append({"kind": section.group(1), "line": number, "names": set()})
            continue
        key = _KEY.match(line)
        if key and sections:
            sections[-1]["names"].add(key.group(1))
            if key.group(1) == "PrivateKey":
                keys.append({"line": number, "type": "WireGuard PrivateKey",
                             "description": "private key material: a WireGuard X25519 "
                                            "private key (wg genkey)",
                             "key_algorithm": "X25519"})
    if not any(s["kind"] == "Interface" and "PrivateKey" in s["names"] for s in sections):
        return [], []
    rows = []
    for s in sections:
        if not s["names"] & {"PrivateKey", "PublicKey"}:
            continue
        psk = ("; this peer sets a PresharedKey, the symmetric layer WireGuard documents for "
               "post-quantum resistance" if "PresharedKey" in s["names"] else
               "; no PresharedKey is set" if s["kind"] == "Peer" else "")
        rows.append({"line": s["line"], "algorithm": "X25519", "evidence_kind": "declaration",
                     "excerpt": lines[s["line"] - 1].strip()[:200],
                     "description": (f"WireGuard [{s['kind']}]: key exchange by Curve25519 "
                                     f"ECDH, fixed by the protocol{psk}")})
    return rows, keys
