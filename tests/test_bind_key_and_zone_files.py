"""BIND's DNSSEC key files and zone file names (ZA-OPRAVYANE row 340; fixture L2/20-dnssec).
On 0.41.0 `K*.key` was read and listed as not decoded with 0 evidence, `.private`, `*.db` and
`dsset-*` were skipped by type, and an RSA DNSKEY's size was undetermined even in a `.zone`.

* BIND 9 manual pages, https://bind9.readthedocs.io/en/latest/manpages.html -- dnssec-dsfromkey
  reads a key file "named in the format Knnnn.+aaa+iiiii.key, as generated by" dnssec-keygen.
* RFC 3110, 2, https://www.rfc-editor.org/rfc/rfc3110 -- the RSA public key field is
  "Exponent length 1 or 3 octets", "Exponent", "Modulus remaining space"; "Its length in
  octets is represented as one octet if it is in the range of 1 to 255 and by a zero octet
  followed by a two octet unsigned length if it is longer than 255 bytes."

The key below is a real 1024-bit RSA key (the L2 fixture, generated with `cryptography`).
"""

import base64
import sqlite3

from qrp_mcp.scan import scan_directory

DNSKEY_8 = ("AwEAAaMeZsYVA/FJkc+VQhs/6+di7JU9rSfO2X9/0gg0txb75WobJyStq2a2y8ChxVZax0vmFNhn3T1yYqUwsT3Q"
            "SnwjReXgEOMjQgi+wPeL7hdi0nFm0gL1AlKuyE4Wm8wWLV/PyooKysjIuAQPeLgj7EZyWtBf9G/aBmoea3rnE4y1")
MODULUS = base64.b64encode(base64.b64decode(DNSKEY_8)[4:]).decode()


def _rsa(result, path):
    return [(f["line"], f.get("key_size")) for f in result["evidence"]["source_code"]
            if f["path"] == path and f["algorithm"] == "RSA"]


def test_key_file_is_decoded_with_its_size(tmp_path):
    name = "Kexample.com.+008+12345.key"
    (tmp_path / name).write_text(f"; zone-signing key\nexample.com. IN DNSKEY 256 3 8 {DNSKEY_8}\n")
    result = scan_directory(tmp_path)
    assert _rsa(result, name) == [(2, 1024)]
    assert result["claimed_but_not_decoded"] == []
    assert 1024 in result["algorithm_key_sizes_observed"]["RSA"]


def test_private_key_file(tmp_path):
    name = "Kexample.com.+008+12345.private"
    (tmp_path / name).write_text(f"Private-key-format: v1.3\nAlgorithm: 8 (RSASHA256)\n"
                                 f"Modulus: {MODULUS}\nPublicExponent: AQAB\n")
    result = scan_directory(tmp_path)
    assert result["files_read"] == [name]
    assert _rsa(result, name) == [(2, 1024)]
    [key] = result["evidence"]["embedded_keys"]
    assert (key["key_algorithm"], key["key_size"]) == ("RSA", 1024)


def test_zone_file_names(tmp_path):
    (tmp_path / "dsset-example.com.").write_text("example.com. IN DS 54321 13 2 " + "AB" * 32 + "\n")
    (tmp_path / "db.example.com").write_text(f"@ 3600 IN DNSKEY 256 3 8 {DNSKEY_8}\n")
    (tmp_path / "example.com.db").write_text(f"$ORIGIN example.com.\n@ IN DNSKEY 256 3 8 {DNSKEY_8}\n")
    result = scan_directory(tmp_path)
    assert sorted(result["files_read"]) == ["db.example.com", "dsset-example.com.", "example.com.db"]
    assert _rsa(result, "example.com.db") == [(2, 1024)]


def test_a_sqlite_db_stays_unclaimed(tmp_path):
    sqlite3.connect(tmp_path / "app.db").execute("create table t (x)").connection.commit()
    result = scan_directory(tmp_path)
    assert result["files_skipped_by_type"] == {".db": 1}
