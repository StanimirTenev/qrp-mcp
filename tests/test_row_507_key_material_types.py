"""ZA-OPRAVYANE row 507, D13 of `linkedin-postove/2026-11-15/boot-proba/REZULTAT.md` §8
(MCUboot f30be48, U-Boot 6487c50, 0.46.0).

Key material in types no reader claimed, so clause 5 saw no key there:

* MCUboot's `sim/src/*_pub_key-rs.txt`: public keys as a Rust byte array (`imgtool getpub
  --lang rust`), `&[0x30, 0x59, ...]`, the DER SubjectPublicKeyInfo -- now decoded, with the
  family, size and curve, as a public-key PEM is (row 503).
* U-Boot's `doc/chromium/files/devkeys/kernel_data_key.vbprivk`: a Chromium vboot private key,
  an 8-byte algorithm word followed by the DER RSAPrivateKey (the bytes: `04 00 .. 00 30 82 04
  a3`) -- now read from the DER; the size is the modulus's, not the header's.
* `.vbpubk` and `.keyblock` (vboot's own packed-key layout, not DER) are claimed and named as
  not decoded, no longer `type_not_claimed`.

Not done: MCUboot's `enc-aes128kw.b64` / `enc-aes256kw.b64` -- 16 or 32 bytes of base64 with no
structure to read an algorithm from except the file name, and symmetric keys are out of scope
(docs/measurement.md); they stay `type_not_claimed`. Keys are made at test time.
"""

import json
import struct

import pytest

pytest.importorskip("cryptography")
from cryptography.hazmat.primitives import serialization  # noqa: E402
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, rsa  # noqa: E402

from qrp_mcp import cyclonedx, server  # noqa: E402
from qrp_mcp.scan import scan_directory  # noqa: E402

DER = serialization.Encoding.DER
SPKI = serialization.PublicFormat.SubjectPublicKeyInfo


def _rust(name, der):
    body = ",\n".join("    " + ", ".join(f"0x{b:02x}" for b in der[i:i + 8])
                      for i in range(0, len(der), 8))
    return (f"/* Autogenerated by imgtool.py, do not edit. */\n"
            f"static {name}: &[u8] = &[\n{body},\n];\n"
            f"static {name}_LEN: usize = {len(der)};\n")


@pytest.fixture
def tree(tmp_path):
    t = tmp_path / "repo"
    (t / "sim/src").mkdir(parents=True)
    (t / "devkeys").mkdir()
    ecpub = ec.generate_private_key(ec.SECP256R1()).public_key().public_bytes(DER, SPKI)
    ec384 = ec.generate_private_key(ec.SECP384R1()).public_key().public_bytes(DER, SPKI)
    edpub = ed25519.Ed25519PrivateKey.generate().public_key().public_bytes(DER, SPKI)
    # MCUboot's file holds two arrays, ECDSA256_PUB_KEY and ECDSAP384_PUB_KEY.
    (t / "sim/src/ecdsa_pub_key-rs.txt").write_text(
        _rust("ECDSA256_PUB_KEY", ecpub) + "\n" + _rust("ECDSAP384_PUB_KEY", ec384))
    (t / "sim/src/ed25519_pub_key-rs.txt").write_text(_rust("ED25519_PUB_KEY", edpub))
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    pkcs1 = key.private_bytes(DER, serialization.PrivateFormat.TraditionalOpenSSL,
                              serialization.NoEncryption())
    # vboot's algorithm word 4 is RSA-2048/SHA-256; the size is read from the key, not from it.
    (t / "devkeys/kernel_data_key.vbprivk").write_bytes(struct.pack("<Q", 4) + pkcs1)
    (t / "devkeys/kernel.keyblock").write_bytes(b"CHROMEOS" + bytes(200))
    (t / "devkeys/kernel_subkey.vbpubk").write_bytes(bytes(64))
    (t / "enc-aes128kw.b64").write_text("0VoElcTCqP8weM5Jtfyy3Q==\n")
    return t


def _unclaimed(result):
    return {p for n in result["coverage"]["not_examined"]
            if n.get("reason") == "type_not_claimed" for p in n.get("paths", [])}


def _check(result):
    rows = {(e["path"], e["algorithm"]): e for e in result["evidence"]["source_code"]}
    ecrows = [(e["line"], e["key_size"], e["curve"], e["key_material"])
              for e in result["evidence"]["source_code"]
              if e["path"] == "sim/src/ecdsa_pub_key-rs.txt"]
    assert ecrows == [(3, 256, "P-256", "public key"), (20, 384, "P-384", "public key")], ecrows
    edrow = rows[("sim/src/ed25519_pub_key-rs.txt", "Ed25519")]
    assert (edrow["key_size"], edrow["key_material"]) == (256, "public key")
    vb = rows[("devkeys/kernel_data_key.vbprivk", "RSA")]
    assert vb["key_size"] == 2048 and "key_material" not in vb, vb
    keys = [k for k in result["evidence"]["embedded_keys"]
            if k["path"] == "devkeys/kernel_data_key.vbprivk"]
    assert [(k["key_algorithm"], k["key_size"]) for k in keys] == [("RSA", 2048)], keys
    # A public key is not a committed secret.
    assert not [k for k in result["evidence"]["embedded_keys"] if k["path"].endswith("-rs.txt")]
    unclaimed = _unclaimed(result)
    assert not unclaimed & {"sim/src/ecdsa_pub_key-rs.txt", "devkeys/kernel_data_key.vbprivk",
                            "devkeys/kernel.keyblock", "devkeys/kernel_subkey.vbpubk"}, unclaimed
    undecoded = set(result["coverage"]["examined_without_result"]["paths"])
    assert {"devkeys/kernel.keyblock", "devkeys/kernel_subkey.vbpubk"} <= undecoded, undecoded
    assert "enc-aes128kw.b64" in unclaimed


def test_key_material_in_the_scan_json(tree, tmp_path):
    out = tmp_path / "r.json"
    assert server.scan_to_file([str(tree), "--out", str(out)]) == 0
    _check(json.loads(out.read_text()))


def test_key_material_in_the_mcp_tool(tree):
    _check(server.scan_repo(str(tree)))


def test_key_material_reaches_the_cbom(tree):
    for doc in (server.export_cbom(str(tree)), cyclonedx.build(scan_directory(tree))):
        names = {c["name"] for c in doc["components"]}
        assert {"RSA-2048 private key", "EC-256 public key", "Ed25519-256 public key"} <= names, names


def test_a_text_file_with_other_bytes_is_not_a_key(tmp_path):
    (tmp_path / "table-rs.txt").write_text("static T: &[u8] = &[0x01, 0x02, 0x30, 0x00];\n")
    result = scan_directory(tmp_path)
    assert not result["evidence"]["source_code"]
    undecoded = set(result["coverage"]["examined_without_result"]["paths"])
    assert "table-rs.txt" in undecoded
